DxfWriter::DxfWriter(const Document& doc) : m_doc(doc) {}

DxfSaveResult DxfWriter::save(const std::string& filePath) {
    DxfSaveResult result;

    // Atomic save: write to temp file first, then rename
    std::string tempPath = filePath + ".tmp";

    try {
        DxfWriterAdapter adapter(m_doc);
        dxfRW writer(tempPath.c_str());
        adapter.setWriter(&writer);

        bool ok = writer.write(&adapter, DRW::AC1027, false); // AC1027 = DXF 2013, ASCII
        if (!ok) {
            result.errorMessage = "Failed to write DXF data";
            std::filesystem::remove(tempPath);
            return result;
        }

        // Atomic rename: remove old file, rename temp
        std::error_code ec;
        if (std::filesystem::exists(filePath)) {
            std::filesystem::remove(filePath, ec);
            if (ec) {
                result.errorMessage = "Cannot overwrite existing file: " + ec.message();
                std::filesystem::remove(tempPath);
                return result;
            }
        }

        std::filesystem::rename(tempPath, filePath, ec);
        if (ec) {
            result.errorMessage = "Failed to finalize save (rename): " + ec.message();
            return result;
        }

        result.success = true;
        result.entityCount = m_doc.entityCount();

    } catch (const std::exception& e) {
        result.errorMessage = std::string("Exception during save: ") + e.what();
        std::filesystem::remove(tempPath);
    }

    return result;
}

std::string DxfWriter::generateFilename(int month, int day, int seq,
                                         const std::string& company,
                                         const std::string& drawingName,
                                         const std::string& jeolsu) {
    std::ostringstream oss;
    oss << std::setfill('0') << std::setw(2) << month
        << std::setw(2) << day
        << "-" << seq
        << " " << company
        << " " << drawingName
        << " " << jeolsu
        << ".DXF";
    return oss.str();
}

