/// Internal writer interface for libdxfrw
class DxfWriterAdapter : public DRW_Interface {
public:
    explicit DxfWriterAdapter(const Document& doc) : m_doc(doc) {}

    void writeHeader(DRW_Header& header) override {
        // Set basic header values
        header.addComment("Generated by YJ-CAD");
    }

    void writeLayers() override {
        for (const auto& name : m_doc.layers().layerNames()) {
            const auto* layer = m_doc.layers().layer(name);
            if (!layer) continue;

            DRW_Layer drwLayer;
            drwLayer.name = layer->name();
            drwLayer.color = layer->color();
            if (layer->isFrozen()) drwLayer.flags |= 0x01;
            if (layer->isLocked()) drwLayer.flags |= 0x04;
            m_writer->writeLayer(&drwLayer);
        }
    }

    void writeEntities() override {
        for (EntityId id : m_doc.entityIds()) {
            const auto* entity = m_doc.entity(id);
            if (!entity) continue;

            switch (entity->type()) {
                case EntityType::Line: writeLine(static_cast<const LineEntity*>(entity)); break;
                case EntityType::Circle: writeCircle(static_cast<const CircleEntity*>(entity)); break;
                case EntityType::Arc: writeArc(static_cast<const ArcEntity*>(entity)); break;
                case EntityType::Polyline: writePolyline(static_cast<const PolylineEntity*>(entity)); break;
                case EntityType::Text: writeText(static_cast<const TextEntity*>(entity)); break;
                default: break;
            }
        }
    }

    void setWriter(dxfRW* writer) { m_writer = writer; }

    // Stubs for unused callbacks
    void addHeader(const DRW_Header*) override {}
    void addLType(const DRW_LType&) override {}
    void addLayer(const DRW_Layer&) override {}
    void addDimStyle(const DRW_Dimstyle&) override {}
    void addVport(const DRW_Vport&) override {}
    void addTextStyle(const DRW_Textstyle&) override {}
    void addAppId(const DRW_AppId&) override {}
    void addBlock(const DRW_Block&) override {}
    void setBlock(const int) override {}
    void endBlock() override {}
    void addPoint(const DRW_Point&) override {}
    void addLine(const DRW_Line&) override {}
    void addRay(const DRW_Ray&) override {}
    void addXline(const DRW_Xline&) override {}
    void addArc(const DRW_Arc&) override {}
    void addCircle(const DRW_Circle&) override {}
    void addEllipse(const DRW_Ellipse&) override {}
    void addLWPolyline(const DRW_LWPolyline&) override {}
    void addPolyline(const DRW_Polyline&) override {}
    void addSpline(const DRW_Spline*) override {}
    void addKnot(const DRW_Entity&) override {}
    void addInsert(const DRW_Insert&) override {}
    void addTrace(const DRW_Trace&) override {}
    void add3dFace(const DRW_3Dface&) override {}
    void addSolid(const DRW_Solid&) override {}
    void addMText(const DRW_MText&) override {}
    void addText(const DRW_Text&) override {}
    void addDimAlign(const DRW_DimAligned*) override {}
    void addDimLinear(const DRW_DimLinear*) override {}
    void addDimRadial(const DRW_DimRadial*) override {}
    void addDimDiametric(const DRW_DimDiametric*) override {}
    void addDimAngular(const DRW_DimAngular*) override {}
    void addDimAngular3P(const DRW_DimAngular3p*) override {}
    void addDimOrdinate(const DRW_DimOrdinate*) override {}
    void addLeader(const DRW_Leader*) override {}
    void addHatch(const DRW_Hatch*) override {}
    void addViewport(const DRW_Viewport&) override {}
    void addImage(const DRW_Image*) override {}
    void linkImage(const DRW_ImageDef*) override {}
    void addComment(const char*) override {}
    void addPlotSettings(const DRW_PlotSettings*) override {}
    void writeBlocks() override {}
    void writeBlockRecords() override {}
    void writeLTypes() override {}
    void writeTextstyles() override {}
    void writeVports() override {}
    void writeDimstyles() override {}
    void writeAppId() override {}
    void writeObjects() override {}

private:
    void applyCommon(DRW_Entity& drw, const Entity* e) {
        drw.layer = e->layerName();
        drw.color = e->color();
        drw.lWeight = static_cast<DRW_LW_Conv::lineWidth>(
            static_cast<int>(e->lineWidth() * 100));
    }

    void writeLine(const LineEntity* e) {
        DRW_Line drw;
        applyCommon(drw, e);
        drw.basePoint = DRW_Coord(e->start().x, e->start().y, 0);
        drw.secPoint = DRW_Coord(e->end().x, e->end().y, 0);
        m_writer->writeLine(&drw);
    }

    void writeCircle(const CircleEntity* e) {
        DRW_Circle drw;
        applyCommon(drw, e);
        drw.basePoint = DRW_Coord(e->center().x, e->center().y, 0);
        drw.radious = e->radius();
        m_writer->writeCircle(&drw);
    }

    void writeArc(const ArcEntity* e) {
        DRW_Arc drw;
        applyCommon(drw, e);
        drw.basePoint = DRW_Coord(e->center().x, e->center().y, 0);
        drw.radious = e->radius();
        constexpr double DEG2RAD = 3.14159265358979323846 / 180.0;
        drw.staangle = e->startAngle() * DEG2RAD;
        drw.endangle = e->endAngle() * DEG2RAD;
        m_writer->writeArc(&drw);
    }

    void writePolyline(const PolylineEntity* e) {
        DRW_LWPolyline drw;
        applyCommon(drw, e);
        if (e->isClosed()) drw.flags |= 0x01;
        for (const auto& v : e->vertices()) {
            drw.addVertex(DRW_Vertex2D(v.x, v.y, 0));
        }
        m_writer->writeLWPolyline(&drw);
    }

    void writeText(const TextEntity* e) {
        DRW_Text drw;
        applyCommon(drw, e);
        drw.basePoint = DRW_Coord(e->position().x, e->position().y, 0);
        drw.height = e->height();
        drw.text = e->text();
        drw.angle = e->rotation();
        m_writer->writeText(&drw);
    }

    const Document& m_doc;
    dxfRW* m_writer = nullptr;
};

